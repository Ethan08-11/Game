function effectKey(raw: string): { key: string; nums: string[] } {
  const norm = raw
    .replace(/\s+/g, '')
    .replace(/~/g, '～')
    .replace(/[xX]/g, '×')
    .replace(/[－—–−-]/g, '-')
    .replace(/＋/g, '+')
  return { key: norm.replace(/\d+/g, '{}'), nums: norm.match(/\d+/g) ?? [] }
}

export function translateEffectTemplate(raw: string): string | null {
  const { key, nums } = effectKey(raw)
  const pattern = EFFECT_EN[key]
  if (!pattern) return null
  return pattern.replace(/\{(\d+)\}/g, (_, index) => nums[Number(index)] ?? '')
}

function stemFromImageUrl(imageUrl?: string | null): string {
  if (!imageUrl) return ''
  try {
    const path = imageUrl.split('?')[0].split('#')[0]
    const file = decodeURIComponent(path.split('/').pop() || '')
    return file.replace(/\.[^.]+$/, '')
  } catch {
    return ''
  }
}

/** 卡面名字/职位在卷轴上的 top 百分比。 */
export function cardNameTopPercent(imageUrl?: string | null, cardName?: string | null): number {
  const stem = stemFromImageUrl(imageUrl)
  if (stem && NAME_TOP_BY_STEM[stem] != null) return NAME_TOP_BY_STEM[stem]
  const name = (cardName || '').trim()
  if (name && NAME_TOP_BY_CARD_NAME[name] != null) return NAME_TOP_BY_CARD_NAME[name]
  if (/^Card_/i.test(stem)) return 63.5
  return DEFAULT_CARD_NAME_TOP
}
